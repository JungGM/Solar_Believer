"""PostgreSQL-only collector persistence. There is no local database fallback."""

import hashlib
import os
from pathlib import Path
import json

import psycopg
from psycopg import sql
from psycopg.types.json import Jsonb

from backend.app.config import get_settings

TEST_SCHEMAS = set()
TEST_STORES = []


def schema_name(directory):
    directory = Path(directory).resolve()
    root = Path(__file__).resolve().parents[1] / "data"
    try:
        logical = directory.relative_to(root).as_posix()
    except ValueError:
        logical = str(directory)
    prefix = os.environ.get("COLLECTOR_TEST_PREFIX", "collector")
    return prefix + "_" + hashlib.sha256(logical.encode()).hexdigest()[:20]


def connect_postgres():
    config = get_settings()
    return psycopg.connect(
        host=config.postgres_host,
        port=config.postgres_port,
        dbname=config.postgres_db,
        user=config.postgres_user,
        password=config.postgres_password,
        connect_timeout=10,
    )


def store_exists(directory):
    with connect_postgres() as conn:
        return conn.execute(
            "SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname=%s)", (schema_name(directory),)
        ).fetchone()[0]


def persist_runtime_state(path, document):
    root = Path(__file__).resolve().parents[1] / "data"
    try:
        relative = Path(path).resolve().relative_to(root.resolve())
    except ValueError:
        return
    if not (
        relative.name.endswith("queue.json")
        or relative.name.endswith("status.json")
        or relative.parts[0] == "source_catalogs"
    ):
        return
    with connect_postgres() as conn:
        conn.execute("""CREATE TABLE IF NOT EXISTS public.collector_runtime_state(
            name TEXT PRIMARY KEY,document JSONB NOT NULL,updated_at TIMESTAMPTZ DEFAULT now())""")
        conn.execute(
            """INSERT INTO public.collector_runtime_state(name,document) VALUES(%s,%s)
            ON CONFLICT(name) DO UPDATE SET document=excluded.document,updated_at=now()""",
            (relative.as_posix(), Jsonb(document)),
        )


def restore_runtime_state(destination=None):
    root = Path(destination) if destination is not None else Path(__file__).resolve().parents[1] / "data"
    with connect_postgres() as conn:
        exists = conn.execute("SELECT to_regclass('public.collector_runtime_state')").fetchone()[0]
        if not exists:
            return 0
        rows = conn.execute("SELECT name,document FROM public.collector_runtime_state").fetchall()
    for name, document in rows:
        target = (root / name).resolve()
        if not target.is_relative_to(root.resolve()):
            raise ValueError("Invalid collector state path")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    return len(rows)


class Record(tuple):
    def __new__(cls, values, names):
        obj = super().__new__(cls, values)
        obj.names = names
        return obj

    def __getitem__(self, key):
        return super().__getitem__(self.names.index(key) if isinstance(key, str) else key)


class Result:
    def __init__(self, cursor):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.names = [col.name for col in cursor.description] if cursor.description else []

    def fetchone(self):
        value = self.cursor.fetchone()
        return Record(value, self.names) if value is not None else None

    def fetchall(self):
        return [Record(value, self.names) for value in self.cursor.fetchall()]

    def __iter__(self):
        for value in self.cursor:
            yield Record(value, self.names)

    @property
    def lastrowid(self):
        return self.fetchone()[0]


PUBLIC_DDL = """
CREATE TABLE IF NOT EXISTS requests(id TEXT PRIMARY KEY,status TEXT,path TEXT,metadata TEXT);
CREATE TABLE IF NOT EXISTS calls(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at TEXT,day TEXT);
CREATE TABLE IF NOT EXISTS records(day TEXT,resource TEXT,payload TEXT,fetched TEXT,request_id TEXT,PRIMARY KEY(day,resource));
CREATE TABLE IF NOT EXISTS revisions(day TEXT,resource TEXT,payload TEXT,fetched TEXT,request_id TEXT);
"""
USAGE_DDL = """
CREATE TABLE IF NOT EXISTS calls(id TEXT PRIMARY KEY,source TEXT,at TEXT,day TEXT);
CREATE INDEX IF NOT EXISTS source_day ON calls(source,day);
CREATE UNIQUE INDEX IF NOT EXISTS source_call_time ON calls(source,at);
CREATE TABLE IF NOT EXISTS blocks(source TEXT,day TEXT,reason TEXT,PRIMARY KEY(source,day));
"""
KMA_DDL = """
CREATE TABLE IF NOT EXISTS tasks(id TEXT PRIMARY KEY,kind TEXT,day TEXT,params TEXT,priority INTEGER,
state TEXT DEFAULT 'pending',attempts INTEGER DEFAULT 0,due DOUBLE PRECISION DEFAULT 0,
path TEXT,summary TEXT,error TEXT,fetched TEXT);
CREATE INDEX IF NOT EXISTS due_tasks ON tasks(kind,state,due,priority,day,id);
CREATE TABLE IF NOT EXISTS calls(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,day TEXT,at TEXT,bytes BIGINT,status TEXT);
CREATE INDEX IF NOT EXISTS calls_by_day ON calls(day);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT);
CREATE TABLE IF NOT EXISTS observations(tm TEXT,stn TEXT,payload TEXT,fetched TEXT,PRIMARY KEY(tm,stn));
"""


class PostgresStore:
    def __init__(self, directory, kind="public"):
        self.directory = Path(directory)
        self.kind = kind
        self.schema = schema_name(directory)
        self.connection = connect_postgres()
        self.total_changes = 0
        self.connection.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,0))", (self.schema,))
        self.connection.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(self.schema)))
        self.connection.execute(sql.SQL("SET search_path TO {},public").format(sql.Identifier(self.schema)))
        self.executescript({"public": PUBLIC_DDL, "usage": USAGE_DDL, "kma": KMA_DDL}[kind])
        self.execute(
            "CREATE TABLE IF NOT EXISTS raw_responses(path TEXT PRIMARY KEY,body_gzip BYTEA NOT NULL,metadata JSONB NOT NULL)"
        )
        self.commit()
        if os.environ.get("COLLECTOR_TEST_PREFIX"):
            TEST_SCHEMAS.add(self.schema)
            TEST_STORES.append(self)

    def execute(self, statement, params=()):
        cursor = self.connection.execute(statement.replace("?", "%s"), params)
        if not cursor.description:
            self.total_changes += max(cursor.rowcount, 0)
        return Result(cursor)

    def executemany(self, statement, rows):
        cursor = self.connection.cursor()
        cursor.executemany(statement.replace("?", "%s"), rows)
        self.total_changes += max(cursor.rowcount, 0)
        return Result(cursor)

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def store_raw(self, path, compressed, metadata):
        self.connection.execute(
            "INSERT INTO raw_responses VALUES(%s,%s,%s) ON CONFLICT(path) DO NOTHING",
            (str(path), compressed, Jsonb(metadata)),
        )

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        self.rollback() if exc_type else self.commit()
        self.close()


def open_store(directory, kind="public"):
    return PostgresStore(directory, kind)
